#!/usr/bin/env python3
"""Generates test/http/structured_field_tests.hpp: the httpwg's Structured Fields tests
(https://github.com/httpwg/structured-field-tests), which Structured Fields' tests parse.

    git clone https://github.com/httpwg/structured-field-tests.git
    python3 tools/structured_fields/gen_tests.py structured-field-tests > test/http/structured_field_tests.hpp

Every parsing test is taken (Items, Lists and Dictionaries), but large-generated.json's, whose values (up to 22 KB
each) the tests make themselves, and serialisation-tests/, which are for serializers. Each case keeps its field lines
as they are, whether it must (or may) fail, and the canonical form it parses to if that isn't its lines joined with
", " (its "canonical"), which the tests compare with what they serialize from what's parsed. A case a line, unformatted
(clang-format would spread each over several).
"""

import json
import os
import subprocess
import sys

SKIPPED = {"large-generated.json"}

# the most field lines a case has.
MAX_LINES = 3


def literal(s):
    """A C++ string_view literal of s's UTF-8 bytes: printable ASCII as it is, the rest as 3-digit octal escapes (which
    can't run into a following digit). A string_view literal, as some have NULs."""
    out = '"'
    for b in s.encode("utf-8"):
        c = chr(b)
        if c in '\\"':
            out += "\\" + c
        elif " " <= c <= "~":
            out += c
        else:
            out += f"\\{b:03o}"
    return out + '"sv'


def main(root):
    commit = subprocess.run(
        ["git", "-C", root, "rev-parse", "HEAD"], capture_output=True, text=True, check=True
    ).stdout.strip()
    with open(os.path.join(root, "LICENSE.md"), encoding="utf-8") as f:
        license_text = f.read().strip()

    cases = []
    for name in sorted(os.listdir(root)):
        if not name.endswith(".json") or name in SKIPPED:
            continue
        with open(os.path.join(root, name), encoding="utf-8") as f:
            for test in json.load(f):
                raw = test["raw"]
                assert 1 <= len(raw) <= MAX_LINES, (name, test["name"])
                must_fail = test.get("must_fail", False)
                canonical = None
                if not must_fail:
                    canonical = ", ".join(test.get("canonical", raw))
                cases.append((f"{name}: {test['name']}", test["header_type"], raw, must_fail,
                              test.get("can_fail", False), canonical))

    out = [
        "#pragma once",
        "",
        "// Generated by tools/structured_fields/gen_tests.py from structured-field-tests",
        f"// (https://github.com/httpwg/structured-field-tests, commit {commit}):",
        "// its parsing tests. Its license:",
        "//",
    ]
    out += [("// " + line).rstrip() for line in license_text.splitlines()]
    out += [
        "",
        "#include <array>",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <optional>",
        "#include <string_view>",
        "",
        "namespace structured_field_tests",
        "{",
        "",
        "// kind is what a case's value is parsed as.",
        "enum class kind : std::uint8_t",
        "{",
        "    item,",
        "    list,",
        "    dictionary,",
        "};",
        "",
        "// outcome is whether parsing must succeed, must fail, or may fail (a SHOULD of RFC 9651's).",
        "enum class outcome : std::uint8_t",
        "{",
        "    pass,",
        "    must_fail,",
        "    can_fail,",
        "};",
        "",
        "using enum kind;",
        "using enum outcome;",
        "using namespace std::string_view_literals;",
        "",
        "// test_case is a field's lines (the first line_count of lines), what they're parsed as and whether that must (or",
        "// may) fail, and the canonical form of what they parse to (serialized, RFC 9651, section 4.1), if it isn't the",
        "// lines joined with \", \".",
        "struct test_case",
        "{",
        "    std::string_view                name;",
        "    structured_field_tests::kind    kind = item;",
        f"    std::array<std::string_view, {MAX_LINES}> lines;",
        "    std::size_t                     line_count = 1;",
        "    structured_field_tests::outcome outcome    = pass;",
        "    std::optional<std::string_view> canonical;",
        "};",
        "",
        "// A case a line, its fields in order (designating them would double the file's size), and its strings escaped",
        "// alike (some need octal escapes, which raw literals can't have).",
        "// clang-format off",
        "// NOLINTBEGIN(modernize-use-designated-initializers,modernize-raw-string-literal)",
        f"inline constexpr std::array<test_case, {len(cases)}> cases{{{{",
    ]
    for label, kind, raw, must_fail, can_fail, canonical in cases:
        outcome = "must_fail" if must_fail else ("can_fail" if can_fail else "pass")
        lines = [literal(line) for line in raw] + ["{}"] * (MAX_LINES - len(raw))
        fields = [literal(label), kind, "{" + ", ".join(lines) + "}", str(len(raw)), outcome, "std::nullopt"]
        if canonical is not None and canonical != ", ".join(raw):
            fields[-1] = literal(canonical)
        out.append("    {" + ", ".join(fields) + "},")
    out += ["}};", "// NOLINTEND(modernize-use-designated-initializers,modernize-raw-string-literal)", "// clang-format on", "", "}"]
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
