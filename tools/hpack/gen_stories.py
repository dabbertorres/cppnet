#!/usr/bin/env python3
"""Generates test/http/hpack_stories.hpp: some of hpack-test-case's stories (https://github.com/http2jp/hpack-test-case),
which HPACK's tests decode, as other implementations encoded them.

    git clone https://github.com/http2jp/hpack-test-case.git
    python3 tools/hpack/gen_stories.py hpack-test-case > test/http/hpack_stories.hpp
    clang-format -i test/http/hpack_stories.hpp

The stories (STORIES) are a series of requests (story_02) and of responses (story_24), each as encoded by
implementations chosen for what they use: without Huffman coding and with the dynamic table (haskell-http2-linear),
with both (swift-nio-hpack-huffman), and with the table's size changing between header blocks
(nghttp2-change-table-size). Each case's headers are the same in every implementation's story (raw-data's), so they're
written once per story.
"""

import json
import os
import subprocess
import sys

STORIES = ["story_02", "story_24"]
IMPLEMENTATIONS = ["haskell-http2-linear", "swift-nio-hpack-huffman", "nghttp2-change-table-size"]

# the longest a line of a wire's hex is split into.
HEX_LINE = 96


def escape(s):
    out = ""
    for c in s:
        if c in '\\"':
            out += "\\" + c
        elif " " <= c <= "~":
            out += c
        else:
            raise ValueError(f"unexpected character {c!r}")
    return out


def identifier(s):
    return s.replace("-", "_")


def load(root, implementation, story):
    with open(os.path.join(root, implementation, story + ".json"), encoding="utf-8") as f:
        cases = json.load(f)["cases"]
    return [
        (
            case.get("header_table_size") or 0,
            case["wire"],
            [(name, value) for header in case["headers"] for name, value in header.items()],
        )
        for case in cases
    ]


def main(root):
    commit = subprocess.run(
        ["git", "-C", root, "rev-parse", "HEAD"], capture_output=True, text=True, check=True
    ).stdout.strip()
    with open(os.path.join(root, "LICENSE"), encoding="utf-8") as f:
        license_text = f.read().strip()

    out = [
        "#pragma once",
        "",
        "// Generated by tools/hpack/gen_stories.py from hpack-test-case (https://github.com/http2jp/hpack-test-case,",
        f"// commit {commit}): some of its stories, as other HPACK implementations encoded them. Its license:",
        "//",
    ]
    out += [("// " + line).rstrip() for line in license_text.splitlines()]
    out += [
        "",
        "#include <array>",
        "#include <cstddef>",
        "#include <span>",
        "#include <string_view>",
        "",
        "namespace hpack_stories",
        "{",
        "",
        "// field is a header field (as a story's JSON has it).",
        "struct field",
        "{",
        "    std::string_view name;",
        "    std::string_view value;",
        "};",
        "",
        "// story_case is a header block: the table size SETTINGS gave just before it (0 if it's unchanged), its encoding",
        "// (hex), and how many of its story's fields it decodes to (the next, after those of the cases before it).",
        "struct story_case",
        "{",
        "    std::size_t      header_table_size = 0;",
        "    std::string_view wire;",
        "    std::size_t      fields = 0;",
        "};",
        "",
        "// story is a series of header blocks, which one decoder decodes in order.",
        "struct story",
        "{",
        "    std::string_view            name;",
        "    std::span<const field>      fields;",
        "    std::span<const story_case> cases;",
        "};",
        "",
    ]

    story_list = []
    for story in STORIES:
        headers = None
        for implementation in IMPLEMENTATIONS:
            cases = load(root, implementation, story)
            if headers is None:
                headers = [fields for _, _, fields in cases]
                flat = [f for fields in headers for f in fields]
                out.append(f"inline constexpr std::array<field, {len(flat)}> {story}_fields{{{{")
                out += [f'    {{.name = "{escape(n)}", .value = "{escape(v)}"}},' for n, v in flat]
                out += ["}};", ""]
            assert [fields for _, _, fields in cases] == headers, (implementation, story)

            name = f"{identifier(implementation)}_{story}"
            out.append(f"inline constexpr std::array<story_case, {len(cases)}> {name}{{{{")
            for size, wire, fields in cases:
                parts = [wire[i : i + HEX_LINE] for i in range(0, len(wire), HEX_LINE)] or [""]
                out.append(f"    story_case{{.header_table_size = {size},")
                out.append(f'               .wire = "{parts[0]}"')
                out += [f'                       "{p}"' for p in parts[1:]]
                out[-1] += ","
                out.append(f"               .fields = {len(fields)}}},")
            out += ["}};", ""]
            story_list.append((f"{implementation}/{story}", f"{story}_fields", name))

    out.append(f"inline constexpr std::array<story, {len(story_list)}> stories{{{{")
    out += [f'    {{.name = "{label}", .fields = {fields}, .cases = {cases}}},' for label, fields, cases in story_list]
    out += ["}};", "", "}"]
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
